"""Generate the repo-root README.md (intro + per-network feed tables).

Usage (from anywhere):
    python script/generate-readme.py           # write README.md
    python script/generate-readme.py --check   # exit 1 if README.md is stale
    python script/generate-readme.py --stdout  # print instead of writing

Malformed config files are skipped with a warning on stderr. Output is
deterministic.
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
README = ROOT / 'README.md'
BASE_URL = 'https://config.orakl.network'
NETWORKS = ('mainnet', 'kairos')
INTERVALS = ('fetchInterval', 'aggregateInterval', 'submitInterval')

INTRO = """\
<!-- Generated by script/generate-readme.py — do not edit by hand. CI regenerates it on every PR. -->

# orakl-config

Price-feed configuration for the Orakl Network oracle, per network (`mainnet` = Kaia mainnet, `kairos` = Kaia testnet).

## Served bundles

| network | price feeds |
| --- | --- |
""" + ''.join(
    '| {n} | [`{n}_feeds.json`]({u}/{n}_feeds.json) |\n'.format(n=n, u=BASE_URL)
    for n in NETWORKS
) + """
## Layout

- `config/<network>/<PAIR>.json` — per-pair feed definitions (fetch / aggregate / submit intervals in ms, and the data-source feeds).
- `<network>_feeds.json` — aggregated bundles served from the repo root.

## Applying changes

A merge updates the served bundles; consumers pick them up as follows.

- **Oracle nodes** (`nodebin`): fetcher and aggregator load the bundle only at boot and on config sync, so **any** change (incl. pair-level fields such as `priceSource`, intervals or feeds) reaches them only after `nodebin admin reload` runs inside each node pod/host (or the node restarts). It runs config sync, then fetcher and aggregator refresh, and reads `ADMIN_TOKEN` itself, e.g. `kubectl -n orakl exec <pod> -c orakl-node -- nodebin admin reload` for every pod of the node. A reload logs about one `failed to get message from topic: context canceled` line per config; it is harmless (Bisonai/orakl#2985). The node's reporter is not touched by `admin reload`; it reloads on its own like the DAL (next item).
- **Node reporter, DAL and sentinel** (DAL and on-chain checkers) poll every `CONFIG_RELOAD_INTERVAL` (default 5m) and apply only added or removed pairs; reporter and DAL also reload on SIGHUP (sentinel has no SIGHUP handler: the signal stops it). They refuse an empty bundle or a drop of more than 50 % of pairs; restart them to apply such a change. Sentinel's DAL checker subscribes to websocket feeds only at startup, so added pairs get websocket push tracking after a restart.

See [`script/README.md`](script/README.md) for the scripts that generate the bundles and this file.
"""


def valid_interval(value):
    # Any JSON number, but not bool (which subclasses int).
    return isinstance(value, (int, float)) and not isinstance(value, bool)


def warn(path, msg):
    try:
        shown = path.relative_to(ROOT)
    except ValueError:
        # Path outside the repo (e.g. a test tempdir): show it in full.
        shown = path
    print('skipping {}: {}'.format(shown, msg), file=sys.stderr)


def cell(value):
    return str(value).replace('|', '\\|')


# Display names for non-wss feed sources, keyed by lowercased source name.
# Feed names are `<source>:<BASE>-<QUOTE>` with a lowercase source (#232,
# #297); this maps the source to brand case for the README. Unknown sources
# keep their case.
SOURCE_NAMES = {
    'capybara': 'Capybara',
    'daum': 'Daum',
    'dragonswap': 'DragonSwap',
    'klayswap': 'KlaySwap',
    'naver': 'Naver',
    'pancakeswap': 'PancakeSwap',
    'uniswapv3': 'UniswapV3',
    'uniswapv4': 'UniswapV4',
    'yahoo': 'Yahoo',
}


def display_source(source):
    """Feed source -> README label: drop qualifier (`uniswapv3-0.05` fee tier), canonical case."""
    base = source.split('-', 1)[0]
    return SOURCE_NAMES.get(base.lower(), base)


def source_name(feed):
    """wss feeds -> provider; others (DEX pools, HTTP) -> normalized feed source (before ':')."""
    definition = feed.get('definition')
    if isinstance(definition, dict) and definition.get('type') == 'wss' \
            and isinstance(definition.get('provider'), str):
        return definition['provider']
    name = feed.get('name')
    if isinstance(name, str) and name:
        return display_source(name.split(':', 1)[0]) or None
    return None


def load_pair(path):
    """Return (name, sources, n_feeds, intervals) or None (with a warning) if malformed."""
    try:
        with open(path, encoding="utf-8") as f:
            data = json.load(f)
    except (ValueError, OSError) as err:
        # ValueError covers JSONDecodeError and UnicodeDecodeError
        warn(path, 'could not read/parse JSON ({})'.format(err))
        return None
    if not isinstance(data, dict):
        warn(path, 'top-level JSON is not an object')
        return None
    feeds = data.get('feeds')
    if not isinstance(feeds, list):
        warn(path, '"feeds" missing, null, or not a list')
        return None
    bad = [k for k in INTERVALS if not valid_interval(data.get(k))]
    if not isinstance(data.get('name'), str):
        bad.insert(0, 'name')
    if bad:
        warn(path, 'field(s) missing or not the expected type: {}'.format(', '.join(bad)))
        return None
    sources = {source_name(feed) for feed in feeds if isinstance(feed, dict)}
    sources.discard(None)
    if feeds and not sources:
        warn(path, 'no feed has a usable name/provider')
        return None
    # Prefixes not in SOURCE_NAMES may still vary in case; list each source
    # once, keeping the first spelling in (casefold, exact) order.
    unique = {}
    for s in sorted(sources, key=lambda s: (s.lower(), s)):
        unique.setdefault(s.lower(), s)
    return data['name'], list(unique.values()), len(feeds), [data[k] for k in INTERVALS]


def network_table(network):
    rows = []
    feed_total = 0
    for path in sorted((ROOT / 'config' / network).glob('*.json')):
        pair = load_pair(path)
        if pair is None:
            continue
        name, sources, n_feeds, intervals = pair
        feed_total += n_feeds
        link = path.relative_to(ROOT).as_posix()
        rows.append('| [{}]({}) | {} | {} |'.format(
            cell(name), link, cell(', '.join(sources)), ' | '.join(cell(v) for v in intervals)))
    lines = [
        '## {}'.format(network.capitalize()),
        '',
        '{} pairs, {} feeds.'.format(len(rows), feed_total),
        '',
        '| pair | sources | ' + ' | '.join(INTERVALS) + ' |',
        '| --- | --- | ' + ' | '.join('---:' for _ in INTERVALS) + ' |',
    ] + rows
    return '\n'.join(lines) + '\n'


def render():
    return '\n'.join([INTRO] + [network_table(n) for n in NETWORKS])


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group()
    group.add_argument('--check', action='store_true', help='exit 1 if README.md is out of date')
    group.add_argument('--stdout', action='store_true', help='print to stdout instead of writing README.md')
    args = parser.parse_args()

    content = render()
    if args.stdout:
        sys.stdout.write(content)
        return 0
    current = README.read_text(encoding='utf-8') if README.exists() else ''
    if args.check:
        if current != content:
            print('README.md is out of date; run: python script/generate-readme.py', file=sys.stderr)
            return 1
        return 0
    if current != content:
        README.write_text(content, encoding='utf-8')
    return 0


if __name__ == '__main__':
    sys.exit(main())
